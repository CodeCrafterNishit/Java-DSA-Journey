package Operators;
public class RelationalOperator {
    public static void main(String[] args) {
        int A = 100;
        int B = 50;
        System.out.println((A == B));
        System.out.println((A != B));
        System.out.println((A > B));
        System.out.println((A < B));
        System.out.println((A >= B));
        System.out.println((A <= B));
    }
}
